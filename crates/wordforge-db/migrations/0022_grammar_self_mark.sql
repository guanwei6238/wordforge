-- 「我會了」是使用者說的話，不是排程算出來的數字。
--
-- ## 為什麼要多一個欄位
--
-- 原本按「我會了」只是送一次 FSRS 的 Good 評分。問題是初始 stability
-- （`fsrs.rs` 的 w2）只有 3.17 天，而「已學會」的門檻是 21 天——
-- **按一次根本到不了**，畫面按完仍然顯示「在學」，而使用者不知道
-- 自己按的那一下去了哪裡。要按四五次、隔好幾天，才會翻過去。
--
-- 那個門檻本身沒有錯：21 天是「撐得過三週不複習」的證據門檻，跟詞彙量
-- 的定義一致，不能為了讓按鈕有反應就調低它。錯的是**拿一個評分去表達
-- 一句話**——自評與排程是兩件事：
--
--   stability   排程算出來的**證據**：你上次答對之後，記憶撐得了多久
--   known_at    使用者自己說的**主張**：我會這個，出題時可以用
--
-- 兩件事都真，而且會不一致（標了「我會」卻在練習裡錯三次是很正常的）。
-- 硬塞進同一個數字，不一致就會變成「畫面說學會了、出題還當他不會」
-- 那種安靜的錯——這個專案踩過同一個形狀的坑：prompt 說他掌握 5200 個字，
-- 驗收只認 stability ≥ 21 天的卡片，於是覆蓋率永遠 0%。
--
-- ## 兩個都算「他會」
--
-- 出題時「他已經會的句型」取兩者的聯集：自評過的，或者練到撐得過 21 天的。
-- 這也是文法頁「已學會」的定義，兩邊必須是同一句 SQL 能表達的同一件事。
--
-- ## 答錯不會自動清掉自評
--
-- 誘惑是「他標了會卻答錯，那就把標記收回來」。不這麼做，兩個理由：
-- 自評是使用者的話，只有他能收回；而且錯誤歸因本身是估計的
-- （偵測到的範圍要跟模型指出的片段重疊才算），拿一個估計去推翻
-- 一句明確的話，方向反了。
--
-- 取而代之的是**把兩件事都顯示出來**：文法頁上同時看得到「你標記過：
-- 我會了」與「練習中答對 3 次、答錯 5 次」。不一致的時候由人決定，
-- 而不是由程式猜。

